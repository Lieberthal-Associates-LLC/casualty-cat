calculateLoss <- function(event, shockStd = 1.0) {
  # returns total loss generated by event
  totalLoss = 0.0
  for(policy in getAffectedPolicies(event)) {
    for(activity in event$activities) {
      if(activity %in% coveredBusinessActivities[[policy]]) {
        shock = rlnorm(1, meanlog = 0, sdlog = shockStd)
        totalLoss = totalLoss + event$severity * policyWeights[[policy]][[activity]] * shock
      }
    }
  }
  return(totalLoss)
}
